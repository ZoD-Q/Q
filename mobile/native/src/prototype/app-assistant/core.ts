import { findInsurance, groups, insuranceTypes, sources, type InsuranceType } from '../insurance/catalog';
import { validateMarketQuery, type MarketQuery } from '../market-data/core';
import { APP_MODULES, appCopy, isModuleId, moduleDefinition, type AppLocale, type ModuleId } from './catalog';

export { APP_MODULES, CAPABILITY_GUIDANCE, MODULE_IDS, describeAppCapabilities, isModuleId } from './catalog';
export type { AppLocale, ModuleId } from './catalog';
export const INSURANCE_TYPE_IDS = insuranceTypes.map(item => item.id);
export const INSURANCE_GROUP_IDS = groups.map(item => item.id);
export const INSURANCE_RESULT_LIMIT = 6;
export type AppCommand =
  | { name: 'app_info'; arguments: { module: ModuleId | 'all' } }
  | { name: 'insurance_search'; arguments: { query: string; group?: string } }
  | { name: 'insurance_compare'; arguments: { ids: string[] } }
  | { name: 'market_query'; arguments: MarketQuery }
  | { name: 'app_open'; arguments: { module: ModuleId; query?: string; insuranceIds?: string[]; marketQuery?: MarketQuery } };
export type AppNavigationAction = {
  module: ModuleId; label: string; query?: string; insuranceIds?: string[];
  /** Generated by the local insurance search, never accepted as an app_open argument. */
  group?: string;
  marketQuery?: MarketQuery;
};
export type AppJson = null | boolean | number | string | AppJson[] | { [key: string]: AppJson };
export type AppReadResult = { text: string; actions: AppNavigationAction[]; data?: AppJson; marketQuery?: MarketQuery };
export class AppCommandError extends Error {
  readonly code = 'APP_INVALID_COMMAND';
  constructor() { super('APP_INVALID_COMMAND'); this.name = 'AppCommandError'; }
}
const invalid = (): never => { throw new AppCommandError(); };
function object(value: unknown): Record<string, unknown> {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return invalid();
  return value as Record<string, unknown>;
}
function keys(value: Record<string, unknown>, required: string[], optional: string[] = []) {
  if (required.some(key => !Object.hasOwn(value, key)) || Object.keys(value).some(key => !required.includes(key) && !optional.includes(key))) invalid();
}
function boundedText(value: unknown, maximum: number, empty = false): string {
  if (typeof value !== 'string' || value.length > maximum * 2 || /[\u0000-\u001f\u007f-\u009f\u202a-\u202e\u2066-\u2069]/.test(value)) return invalid();
  const characters = Array.from(value);
  if (characters.length > maximum || characters.some(char => { const code = char.codePointAt(0)!; return code >= 0xd800 && code <= 0xdfff; })) return invalid();
  const text = value.trim();
  if (!empty && !text) return invalid();
  return text;
}
function ids(value: unknown, minimum: number): string[] {
  if (!Array.isArray(value) || value.length < minimum || value.length > 3
    || value.some(id => typeof id !== 'string' || !INSURANCE_TYPE_IDS.includes(id)) || new Set(value).size !== value.length) return invalid();
  return [...value] as string[];
}
function group(value: unknown): string {
  if (typeof value !== 'string' || (value !== 'all' && !INSURANCE_GROUP_IDS.includes(value))) return invalid();
  return value;
}
function market(value: unknown): MarketQuery {
  try { return validateMarketQuery(value); } catch { return invalid(); }
}
type NavigationParameters = Omit<AppNavigationAction, 'label'>;
function navigationParameters(value: Record<string, unknown>, allowGroup: boolean): NavigationParameters {
  if (!isModuleId(value.module)) return invalid();
  const result: NavigationParameters = { module: value.module };
  if (value.query !== undefined) {
    if (value.module !== 'insurance' || value.insuranceIds !== undefined) return invalid();
    result.query = boundedText(value.query, 120, true);
  }
  if (value.insuranceIds !== undefined) {
    if (value.module !== 'insurance' || value.group !== undefined) return invalid();
    result.insuranceIds = ids(value.insuranceIds, 1);
  }
  if (value.group !== undefined) {
    if (!allowGroup || value.module !== 'insurance') return invalid();
    result.group = group(value.group);
  }
  if (value.marketQuery !== undefined) {
    if (value.module !== 'market-data') return invalid();
    result.marketQuery = market(value.marketQuery);
  }
  return result;
}

/** Validate every boundary, including calls made directly without the server planner. */
export function validateAppCommand(value: unknown): AppCommand {
  const command = object(value); keys(command, ['name', 'arguments']);
  const args = object(command.arguments);
  switch (command.name) {
    case 'app_info':
      keys(args, ['module']);
      if (args.module !== 'all' && !isModuleId(args.module)) return invalid();
      return { name: command.name, arguments: { module: args.module } };
    case 'insurance_search': {
      keys(args, ['query'], ['group']);
      return { name: command.name, arguments: { query: boundedText(args.query, 120, true), ...(args.group === undefined ? {} : { group: group(args.group) }) } };
    }
    case 'insurance_compare':
      keys(args, ['ids']);
      return { name: command.name, arguments: { ids: ids(args.ids, 2) } };
    case 'market_query':
      return { name: command.name, arguments: market(args) };
    case 'app_open': {
      keys(args, ['module'], ['query', 'insuranceIds', 'marketQuery']);
      return { name: command.name, arguments: navigationParameters(args, false) };
    }
    default: return invalid();
  }
}
export function validateAppNavigationAction(value: unknown): AppNavigationAction {
  const action = object(value); keys(action, ['module', 'label'], ['query', 'insuranceIds', 'group', 'marketQuery']);
  const parameters = navigationParameters(action, true);
  const label = boundedText(action.label, 100);
  const title = moduleDefinition(parameters.module).title;
  const labels = [`打开${title[0]}`, `Open ${title[1]}`];
  if (parameters.module === 'insurance' && parameters.insuranceIds && parameters.insuranceIds.length >= 2) labels.push('打开保障方向对比', 'Open coverage comparison');
  if (!labels.includes(label)) return invalid();
  return { ...parameters, label };
}
export function appCommandErrorText(locale: AppLocale): string {
  return locale === 'zh' ? '这项操作暂不支持，或条件不完整。请重新选择模块或查询条件。' : 'This action is unsupported or its conditions are incomplete. Choose a module or query again.';
}
export function createAppNavigationAction(module: ModuleId, locale: AppLocale, extra: Omit<NavigationParameters, 'module'> = {}): AppNavigationAction {
  if (!isModuleId(module)) return invalid();
  const title = appCopy(moduleDefinition(module).title, locale);
  return validateAppNavigationAction({ module, label: locale === 'zh' ? `打开${title}` : `Open ${title}`, ...extra });
}
function accessText(access: typeof APP_MODULES[number]['access'], locale: AppLocale) {
  return locale === 'zh'
    ? access === 'public' ? '公开内容可先查看；具体网络查询仍取决于来源可用性。' : access === 'sign-in' ? '相关账号功能需要登录，当前账号状态需在页面核对。' : '真实业务需要登录并连接自己的供应商或插件；此目录不证明授权已完成。'
    : access === 'public' ? 'Public content can be viewed; network queries still depend on source availability.' : access === 'sign-in' ? 'Account features require sign-in; verify the current account state on the page.' : 'Real business requires sign-in and your own provider or plugin connection; this catalog is not proof of authorization.';
}

// Coverage concepts, rather than complete sample utterances, map to the existing catalog.
const INSURANCE_SYNONYMS: readonly [RegExp, string][] = [
  [/重疾|大病/g, '重大疾病'], [/百万医疗/g, '医疗'], [/车险|汽車保險|汽车保险|车辆保险/g, 'motor'],
  [/猫咪|猫猫|小猫|狗狗|小狗/g, '宠物'], [/雇员|雇員/g, '员工'], [/雇主責任/g, '雇主'],
  [/旅遊|旅游保险/g, '旅游'], [/長期護理/g, '长期护理'], [/責任/g, '责任'], [/醫療/g, '医疗'],
  [/寵物/g, '宠物'], [/意外傷害/g, '意外'], [/重大疾病保險/g, '重大疾病'],
  [/\b(?:serious illness|critical-illness)\b/g, 'critical illness'],
  [/\b(?:car|auto|automobile|vehicle)\b/g, 'motor'], [/\b(?:cat|cats|dog|dogs)\b/g, 'pet'],
  [/\b(?:employee|employees|employer)\b/g, 'employers'], [/\blong term care\b/g, 'long-term care'],
];
export function normalizeInsuranceQuery(query: string): string {
  let normalized = boundedText(query, 120, true).normalize('NFKC').toLowerCase();
  for (const [pattern, replacement] of INSURANCE_SYNONYMS) normalized = normalized.replace(pattern, replacement);
  normalized = normalized.replace(/^(?:请|麻烦)?(?:帮我|替我)?(?:查一下|找一下|查找|搜索|找找|看看|查看|了解一下)?/u, '')
    .replace(/(?:相关介绍|相关资料|的介绍|介绍|有哪些|有什么|怎么了解)[？?。.!！]*$/u, '')
    .replace(/保险|保險|险种|保障(?:介绍|资料)?/gu, '')
    .replace(/(?:^|\s)(?:insurance|cover|coverage|please|find|search|about)(?=\s|$)/g, ' ')
    .replace(/[，、,;；]/g, ' ').trim().replace(/\s+/g, ' ');
  return normalized;
}
const insuranceLimit = (locale: AppLocale) => locale === 'zh'
  ? '这是险种与保障方向的知识导航，不是在售产品清单或购买推荐。具体保障、除外、价格和理赔要求以保险公司条款为准；小Q不报价、不投保、不办理理赔，人工客服尚未接通。'
  : 'This is educational guidance about coverage purposes, not live products or purchase recommendations. Insurer terms determine cover, exclusions, prices and claim requirements. Q does not quote, apply or handle claims; live support is not connected.';
function insuranceSources(locale: AppLocale): AppJson[] {
  return sources.map(source => ({ title: appCopy(source.title, locale), url: source.url }));
}
function insuranceRow(item: InsuranceType, locale: AppLocale): { [key: string]: AppJson } {
  const category = groups.find(group => group.id === item.group)!;
  return { id: item.id, group: item.group, title: appCopy(item.title, locale), coverage: appCopy(item.coverage, locale),
    considerations: locale === 'zh' ? item.caution : category.questions[1],
    questions: appCopy(category.questions, locale), claimPreparation: appCopy(category.claims, locale) };
}
function sourceText(locale: AppLocale): string {
  return sources.map(source => `${appCopy(source.title, locale)}：${source.url}`).join('\n');
}

/** Runs only public local reads; navigation actions need an explicit host UI click. */
export function executeLocalAppCommand(input: AppCommand, locale: AppLocale): AppReadResult {
  const command = validateAppCommand(input);
  const zh = locale === 'zh';
  if (command.name === 'app_info') {
    if (command.arguments.module === 'all') {
      return {
        text: [zh ? '小Q可以按你的目标找到这些模块：' : 'Q can help you find these modules for your goal:',
          ...APP_MODULES.map(item => `${appCopy(item.title, locale)}：${appCopy(item.summary, locale)}`),
          zh ? '目前主对话可读取保险目录与公开市场资料；其他模块提供入口，仍按页面要求登录、连接或确认。未接通的业务和演示不会当作真实办理能力。' : 'This assistant can read insurance metadata and public market data. Other modules offer navigation and keep their page-specific sign-in, connection and confirmation requirements. Demo or disconnected business is not treated as a live service.'].join('\n\n'),
        actions: APP_MODULES.map(item => createAppNavigationAction(item.id, locale)),
        data: { kind: 'app_info', module: 'all', modules: APP_MODULES.map(item => ({ id: item.id, title: appCopy(item.title, locale), assistantRead: item.assistantRead, access: item.access })) },
      };
    }
    const item = moduleDefinition(command.arguments.module);
    return { text: [appCopy(item.title, locale), appCopy(item.summary, locale), appCopy(item.limits, locale), accessText(item.access, locale)].join('\n\n'),
      actions: [createAppNavigationAction(item.id, locale)], data: { kind: 'app_info', module: item.id, title: appCopy(item.title, locale), summary: appCopy(item.summary, locale), limits: appCopy(item.limits, locale), access: item.access, assistantRead: item.assistantRead } };
  }
  if (command.name === 'insurance_search') {
    const query = normalizeInsuranceQuery(command.arguments.query), selectedGroup = command.arguments.group ?? 'all';
    const matches = findInsurance(query, selectedGroup), included = matches.slice(0, INSURANCE_RESULT_LIMIT);
    const title = zh ? `在小Q保险知识目录中找到 ${matches.length} 类保障${matches.length > included.length ? `，先列出 ${included.length} 类` : ''}：` : `Found ${matches.length} coverage entries in Q’s insurance guide${matches.length > included.length ? `; showing the first ${included.length}` : ''}:`;
    const lines = included.map(item => `${appCopy(item.title, locale)}：${appCopy(item.coverage, locale)}`);
    return { text: [title, ...(lines.length ? lines : [zh ? '没有匹配项，可换一个保障关键词或分类。' : 'No matches. Try another coverage term or category.']), insuranceLimit(locale), sourceText(locale)].join('\n\n'),
      actions: [createAppNavigationAction('insurance', locale, { query: Array.from(query).length <= 120 ? query : command.arguments.query, group: selectedGroup })],
      data: { kind: 'insurance_search', query, group: selectedGroup, total: matches.length, included: included.length, records: included.map(item => insuranceRow(item, locale)), sources: insuranceSources(locale), limits: insuranceLimit(locale) } };
  }
  if (command.name === 'insurance_compare') {
    const selected = command.arguments.ids.map(id => insuranceTypes.find(item => item.id === id)!);
    const rows = selected.map(item => insuranceRow(item, locale));
    return { text: [zh ? '按保障目的比较以下险种：' : 'Compare these coverage types by purpose:',
      ...rows.map(row => `${row.title}\n${zh ? '保障方向' : 'Coverage purpose'}：${row.coverage}\n${zh ? '重点核对' : 'Check carefully'}：${row.considerations}\n${zh ? '投保前问题' : 'Questions before buying'}：${row.questions}\n${zh ? '理赔材料参考' : 'Claim-document guidance'}：${row.claimPreparation}`), insuranceLimit(locale), sourceText(locale)].join('\n\n'),
      actions: [{ ...createAppNavigationAction('insurance', locale, { insuranceIds: command.arguments.ids }), label: zh ? '打开保障方向对比' : 'Open coverage comparison' }],
      data: { kind: 'insurance_compare', records: rows, sources: insuranceSources(locale), limits: insuranceLimit(locale) } };
  }
  if (command.name === 'market_query') {
    // This is a request to the network executor, never a completed quote or news result.
    return { text: zh ? '需要读取所选公开来源，尚未取得查询结果。' : 'The selected public source still needs to be queried; no result has been obtained.',
      actions: [createAppNavigationAction('market-data', locale, { marketQuery: command.arguments })], marketQuery: command.arguments,
      data: { kind: 'market_query', pending: true, query: { ...command.arguments } } };
  }
  const item = moduleDefinition(command.arguments.module);
  const destination = createAppNavigationAction(item.id, locale, command.arguments);
  return { text: [zh ? `可以打开${appCopy(item.title, locale)}，继续在页面操作。` : `You can open ${appCopy(item.title, locale)} and continue on that page.`, appCopy(item.summary, locale), appCopy(item.limits, locale),
    zh ? '下面是导航入口，尚未打开页面或办理任何业务。' : 'The action below is a navigation option; no page has been opened and no business action has been performed.'].join('\n\n'),
    actions: [destination], data: { kind: 'app_open', module: item.id, completed: false, limits: appCopy(item.limits, locale) } };
}
